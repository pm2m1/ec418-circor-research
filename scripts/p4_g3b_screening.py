"""G3b literature audit, step 1d: assemble the screening table, PRISMA counts and blank coding sheets (protocol §2, §4).

Inputs: references/g3b/dedup.csv (scripts/p4_g3b_screen_prep.py), references/g3b/screening_decisions.csv (one row per record:
title/abstract decision + reason, full-text decision + reason; decisions by Claude Code, reasons in the protocol's categories),
references/g3b/other_sources.csv (records identified outside the locked searches), references/g3b/search_raw.csv and
search_log.json (for the identification counts).
Checks: every deduplicated record has exactly one decision; every excluded record has a reason; the 11 pilot papers of
docs/P3_G3_AUDIT.md are present and screened.
Writes references/g3b/screening.csv, references/g3b/prisma_counts.json, references/g3b/prisma.md (all counts filled from
prisma_counts.json, none typed by hand) and references/g3b/included.csv. The coding sheets come from
scripts/p4_g3b_sample.py (amendments A1, A2).
usage: .venv/bin/python scripts/p4_g3b_screening.py
"""
import json

import pandas as pd

OUT = "references/g3b"
PILOT = {"Nogueira 2026": "O001", "Nie 2024": "R162", "Patwa 2025": "R215", "Niizumi 2024": "R140", "Zhang ICASSP 2024": "R160",
         "McDonald 2024": "R123", "Walker 2022": "R075", "Elola 2023": "R067", "Vimalajeewa 2025": "R221",
         "Dehghan Manshadi & Mihandoost 2024": "R164", "Ameen 2026": "R244"}

D = pd.read_csv(f"{OUT}/dedup.csv")
O = pd.read_csv(f"{OUT}/other_sources.csv")
S = pd.read_csv(f"{OUT}/screening_decisions.csv", keep_default_na=False)
assert S.record_id.is_unique
assert set(S.record_id) == set(D.record_id) | set(O.record_id), "decision rows must match the records one to one"
assert (S.query("ta_decision == 'exclude'").ta_reason != "").all(), "every title/abstract exclusion needs a reason"
assert (S.query("ft_decision == 'exclude'").ft_reason != "").all(), "every full-text exclusion needs a reason"
assert set(S.query("ta_decision == 'include'").ft_decision) <= {"include", "exclude", "pending"}
meta = pd.concat([D.assign(source_stream="database searches"), O.assign(source_stream="other sources")], ignore_index=True)
T = meta.merge(S, on="record_id", validate="one_to_one")
for name, rid in PILOT.items():
    assert T.set_index("record_id").loc[rid, "ft_decision"] in ("include", "exclude", "pending"), f"pilot {name} not screened"
T["final"] = T.ft_decision.where(T.ta_decision == "include", "exclude")
T.drop(columns=["abstract"]).to_csv(f"{OUT}/screening.csv", index=False)

R = pd.read_csv(f"{OUT}/search_raw.csv")
log = json.load(open(f"{OUT}/search_log.json"))
db = T[T.source_stream == "database searches"]
c = dict(
    identified_by_source={k: int(v) for k, v in R.source.value_counts().items()},
    identified_total=int(len(R)),
    semantic_scholar_queries_blocked=[q for q, v in log["semantic_scholar_retry"]["results"].items() if not v["ok"]],
    duplicates_removed=int(len(R) - len(D)),
    records_screened=int(len(D)),
    ta_excluded=int((db.ta_decision == "exclude").sum()),
    ta_excluded_by_reason={k: int(v) for k, v in db[db.ta_decision == "exclude"].ta_reason.value_counts().items()},
    fulltext_assessed=int((db.ta_decision == "include").sum()),
    fulltext_pending=int((db.ft_decision == "pending").sum()),
    fulltext_excluded=int((db.ft_decision == "exclude").sum()),
    fulltext_excluded_by_reason={k: int(v) for k, v in db[db.ft_decision == "exclude"].ft_reason.value_counts().items()},
    included_from_databases=int((db.final == "include").sum()),
    included_from_other_sources=int(((T.source_stream == "other sources") & (T.final == "include")).sum()),
    included_total=int((T.final == "include").sum()),
    pilot_records=PILOT,
    pilot_status={n: T.set_index("record_id").loc[r, "final"] for n, r in PILOT.items()})
json.dump(c, open(f"{OUT}/prisma_counts.json", "w"), indent=1)

inc = T[T.final == "include"][["record_id", "title", "authors", "year", "venue", "doi", "url", "source_stream", "fulltext_source"]]
inc.to_csv(f"{OUT}/included.csv", index=False)
print(json.dumps({k: v for k, v in c.items() if k not in ("pilot_records",)}, indent=1))

# ---- prisma.md (every number below is read from c)
gs = log["google_scholar"]
src = c["identified_by_source"]
L = ["# G3b PRISMA-style flow (generated by `scripts/p4_g3b_screening.py` from `prisma_counts.json`; do not edit by hand)", "",
     "## Identification",
     f"Locked query (docs/G3B_AUDIT_PROTOCOL.md §1), publication years 2022–2026, searches run {log['date']}. Raw hits: "
     f"**{c['identified_total']}** — " + ", ".join(f"{k} {v}" for k, v in src.items()) + " (`search_raw.csv`, `search_log.json`).",
     "* OpenAlex: boolean title/abstract search plus the citation checks (works citing Oliveira 2022 and the Reyna Challenge "
     "papers, murmur filter).",
     f"* **Semantic Scholar limitation:** the queries {', '.join(repr(q) for q in c['semantic_scholar_queries_blocked'])} returned "
     "HTTP 429 (rate limit) in the main run and again in one retry (≥ 5 s between calls, max 3 tries; "
     "`scripts/p4_g3b_s2_retry.py`). The authors accepted the gap; these terms are covered by OpenAlex and the citation checks.",
     f"* **Google Scholar method:** {gs['method']}; query as locked; {gs['range']}; {gs['order']} order; {gs['per_page']} "
     f"results/page; {gs['pages_captured']} pages captured ({gs['approx_total_hits']} hits); {gs['date']}. {gs['transcription']}. "
     f"Screened: {gs['screened']}. DOIs/URLs are not visible in screenshots, so each record was {gs['resolution'].replace('DOI/URL ', '')}"
     f": {gs['resolved']} resolved by title match, {gs['unresolved']} unresolved (kept with the Scholar metadata). {gs['note']}.",
     "* **Other sources:** " + str(c["included_from_other_sources"]) + " records not retrieved by the locked searches "
     "(`other_sources.csv`): Nogueira et al. 2026 (pilot list; its abstract names CirCor but not \"murmur\", so the locked query "
     "cannot find it) and Ladislaus et al. 2026 (related-work check requested by the authors). Reported separately below.", "",
     "## Deduplication",
     f"By DOI, then normalised title; journal/proceedings version kept and the preprint linked (`dedup.csv`). "
     f"{c['identified_total']} hits − {c['duplicates_removed']} duplicate hits = **{c['records_screened']} unique records**.", "",
     "## Screening (title/abstract, Claude Code; every decision and reason in `screening_decisions.csv` / `screening.csv`)",
     f"Excluded: **{c['ta_excluded']}** — " + "; ".join(f"{k} {v}" for k, v in c["ta_excluded_by_reason"].items()) + ". "
     "(\"Duplicate\" here = the same study reported twice under different titles, e.g. a CinC paper and its journal extension; the "
     "journal version is kept.)", "",
     "## Full-text eligibility",
     f"Assessed: **{c['fulltext_assessed']}**. Excluded at full text: {c['fulltext_excluded']} — "
     + "; ".join(f"{k} {v}" for k, v in c["fulltext_excluded_by_reason"].items()) + ". "
     f"**Pending: {c['fulltext_pending']}** — full text not retrievable by script (paywalled, or the publisher blocks automated "
     "download); eligibility could not be confirmed from the abstract. They stay in `screening.csv` with status `pending` and "
     "must be checked by the team with library access; none is silently dropped.", "",
     "## Included",
     f"From the database searches: **{c['included_from_databases']}**; from other sources: **{c['included_from_other_sources']}**; "
     f"**total {c['included_total']}** (`included.csv`), plus up to {c['fulltext_pending']} pending. All 11 pilot papers of "
     "docs/P3_G3_AUDIT.md are present: " + ", ".join(f"{n} ({c['pilot_records'][n]}: {st})" for n, st in c["pilot_status"].items()) + ".",
     "", "Eligibility of most included records was confirmed from the abstract (a CirCor/PhysioNet 2022 murmur result is stated); "
     "the rest from the full text (see `ft_note`). Coding uses the full text in every case (`evidence_pack.md`)."]
open(f"{OUT}/prisma.md", "w").write("\n".join(L) + "\n")
