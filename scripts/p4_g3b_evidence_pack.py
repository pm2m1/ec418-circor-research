"""G3b literature audit, step 1e: evidence pack for the two human coders (protocol §4). No code is pre-filled.

For every included paper (references/g3b/included.csv): DOI/URL, open-access status (Unpaywall) and, where an open full text can
be retrieved by script (cinc.org PDF for CinC 2022 papers, arXiv, Europe PMC XML, Unpaywall PDF link), CANDIDATE passages for
coding fields 1-3, found by fixed keyword lists and quoted verbatim with their PDF page (or "HTML full text"). Passages are
pointers for the coders, who must read the paper; absence of a passage means nothing. Full texts are cached in
data/interim/g3b_fulltext/ (gitignored, not redistributed).
Writes references/g3b/evidence_pack.md and references/g3b/evidence_pack_index.csv.
usage: .venv/bin/python scripts/p4_g3b_evidence_pack.py
"""
import json
import os
import re
import subprocess
import time
import urllib.parse
import urllib.request

import pandas as pd

OUT, CACHE = "references/g3b", "data/interim/g3b_fulltext"
os.makedirs(CACHE, exist_ok=True)
UA = {"User-Agent": "Mozilla/5.0 (EC418-G3b-audit/1.0; mailto:mishraparth787@gmail.com)"}
KEYS = {
    "Field 1 (segmentation source)": r"annotat|\.tsv|segmentation|segmented|S1 and S2|S1/S2|HSMM|Springer|boundar|expert",
    "Field 2 (evaluation unit)": r"patient[- ]level|per patient|each patient|recording[- ]level|per recording|segment[- ]level|"
                                 r"aggregat|majority vot|snippet|window[- ]level|patient-wise prediction",
    "Field 3 (split)": r"cross[- ]validation|\bfold|train(ing)?/test|split|patient[- ]wise|subject|stratif|hidden test|"
                       r"Additional ID|held[- ]out|leave-one"}
N_PER, W = 3, 230


def get(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60) as f:
        return f.read()


def unpaywall(doi):
    try:
        d = json.loads(get("https://api.unpaywall.org/v2/" + urllib.parse.quote(doi) + "?email=mishraparth787@gmail.com"))
        locs = [l.get("url_for_pdf") for l in d.get("oa_locations") or [] if l.get("url_for_pdf")]
        return d.get("oa_status") or "closed", locs
    except Exception:
        return "unknown", []


def arxiv_id(r):
    for s in [str(r.doi), str(r.url), str(r.fulltext_source)]:
        m = re.search(r"(?:arxiv[./:]|abs/|pdf/)(\d{4}\.\d{4,5})", s, re.I)
        if m:
            return m.group(1)
    return None


def fetch(r, locs):
    """Return a list of (page_label, text) or [] if no full text could be retrieved."""
    base = f"{CACHE}/{r.record_id}"
    cands = []
    m = re.match(r"10\.22489/cinc\.2022\.(\d+)", str(r.doi), re.I)
    if m:
        cands.append(f"https://www.cinc.org/archives/2022/pdf/CinC2022-{int(m.group(1)):03d}.pdf")
    if arxiv_id(r):
        cands.append("https://arxiv.org/pdf/" + arxiv_id(r))
    cands += locs
    if not os.path.exists(base + ".pdf") and not os.path.exists(base + ".xml"):
        for u in dict.fromkeys(cands):
            try:
                b = get(u)
                if b[:4] == b"%PDF":
                    open(base + ".pdf", "wb").write(b)
                    break
            except Exception:
                pass
            time.sleep(1)
        if not os.path.exists(base + ".pdf") and isinstance(r.doi, str) and r.doi:
            try:
                d = json.loads(get("https://www.ebi.ac.uk/europepmc/webservices/rest/search?format=json&resultType=lite&query=" +
                                   urllib.parse.quote(f'DOI:"{r.doi}"')))
                pmc = next((h["pmcid"] for h in d.get("resultList", {}).get("result", []) if h.get("pmcid")), None)
                if pmc:
                    open(base + ".xml", "wb").write(get(f"https://www.ebi.ac.uk/europepmc/webservices/rest/{pmc}/fullTextXML"))
            except Exception:
                pass
    if os.path.exists(base + ".pdf"):
        n = int(re.search(r"Pages:\s+(\d+)", subprocess.run(["pdfinfo", base + ".pdf"], capture_output=True, text=True).stdout or "Pages: 0").group(1))
        return [(f"p. {p}", subprocess.run(["pdftotext", "-f", str(p), "-l", str(p), base + ".pdf", "-"], capture_output=True,
                                            text=True).stdout) for p in range(1, n + 1)]
    if os.path.exists(base + ".xml"):
        x = open(base + ".xml", errors="ignore").read()
        secs = re.findall(r"<sec[^>]*>\s*<title>(.*?)</title>(.*?)</sec>", x, re.S)
        return [(f"section '{re.sub(r'<[^>]+>', '', t).strip()}' (Europe PMC XML)", re.sub(r"<[^>]+>", " ", body)) for t, body in secs] \
            or [("HTML full text (Europe PMC XML)", re.sub(r"<[^>]+>", " ", x))]
    return []


I = pd.read_csv(f"{OUT}/included.csv", keep_default_na=False)
rows, md = [], ["# G3b evidence pack — candidate passages for coding fields 1–3", "",
                "Generated by `scripts/p4_g3b_evidence_pack.py`. For each included paper: links, open-access status and, where a full "
                "text could be retrieved by script, verbatim **candidate** passages found by fixed keyword lists (see the script), "
                "with their page. These are pointers only: coders must read the methods and evaluation sections themselves, a "
                "missing passage means nothing, and no code is suggested here. Papers marked *no open full text* need library access.",
                ""]
for _, r in I.iterrows():
    status, locs = unpaywall(r.doi) if r.doi else ("no DOI", [])
    pages = fetch(r, locs)
    md += [f"## {r.record_id} — {r.title}", f"{r.authors} ({r.year}). *{r.venue}*. "
           + (f"DOI [{r.doi}](https://doi.org/{r.doi})" if r.doi else f"URL {r.url}") + f". Open access: {status}.", ""]
    nq = 0
    if not pages:
        md += ["*No open full text retrieved by script — library access needed.*", ""]
    for field, pat in KEYS.items():
        if not pages:
            break
        hits = []
        for lab, txt in pages:
            t = re.sub(r"\s+", " ", txt)
            for m in re.finditer(pat, t, re.I):
                hits.append((lab, t[max(0, m.start() - W):m.end() + W].strip()))
                if len([h for h in hits if h[0] == lab]) >= 2:
                    break
        # spread over pages: at most N_PER passages, no near-duplicates
        sel = []
        for h in hits:
            if len(sel) < N_PER and all(h[1][:80] != s[1][:80] for s in sel):
                sel.append(h)
        md.append(f"**{field}**")
        md += [f"> {q} — *{lab}*" for lab, q in sel] or ["> (no keyword match)"]
        md.append("")
        nq += len(sel)
    rows.append(dict(record_id=r.record_id, oa_status=status, fulltext_retrieved=bool(pages), n_pages_or_sections=len(pages),
                     n_candidate_passages=nq))
    print(r.record_id, status, len(pages), nq)
open(f"{OUT}/evidence_pack.md", "w").write("\n".join(md))
X = pd.DataFrame(rows)
X.to_csv(f"{OUT}/evidence_pack_index.csv", index=False)
print(f"{len(X)} papers; full text retrieved for {int(X.fulltext_retrieved.sum())}")
